-- ------------------------------------------------------------
-- place: lugares donde se realizan los eventos
-- ------------------------------------------------------------
CREATE TABLE place (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    country     VARCHAR(255) NOT NULL,
    city        VARCHAR(255) NOT NULL,
    place_name  VARCHAR(255) NOT NULL,
    address     VARCHAR(255) NOT NULL,
    capacity    INTEGER      NOT NULL,
    CONSTRAINT pk_place PRIMARY KEY (id)
);

-- ------------------------------------------------------------
-- staff: tabla padre de la jerarquía Staff (JOINED)
-- Guarda los datos comunes de coordinadores, logísticos y managers.
-- ------------------------------------------------------------
CREATE TABLE staff (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    name           VARCHAR(255) NOT NULL,
    email          VARCHAR(255) NOT NULL,
    phone          VARCHAR(255),
    staff_position VARCHAR(255) NOT NULL,
    password       VARCHAR(255) NOT NULL,
    staff_type     VARCHAR(31)  NOT NULL,
    CONSTRAINT pk_staff PRIMARY KEY (id),
    CONSTRAINT uk_staff_email UNIQUE (email)
);

-- ------------------------------------------------------------
-- coordinator: datos propios de los coordinadores
-- El id es a la vez PK y FK hacia staff (herencia JOINED).
-- ------------------------------------------------------------
CREATE TABLE coordinator (
    id      INTEGER      NOT NULL,
    company VARCHAR(255) NOT NULL,
    CONSTRAINT pk_coordinator PRIMARY KEY (id),
    CONSTRAINT fk_coordinator_staff FOREIGN KEY (id) REFERENCES staff (id)
);

-- ------------------------------------------------------------
-- manager: datos propios de los managers
-- ------------------------------------------------------------
CREATE TABLE manager (
    id      INTEGER      NOT NULL,
    company VARCHAR(255) NOT NULL,
    CONSTRAINT pk_manager PRIMARY KEY (id),
    CONSTRAINT fk_manager_staff FOREIGN KEY (id) REFERENCES staff (id)
);

-- ------------------------------------------------------------
-- logistic: datos propios del personal logístico
-- ------------------------------------------------------------
CREATE TABLE logistic (
    id            INTEGER      NOT NULL,
    zone          VARCHAR(255) NOT NULL,
    working_hours INTEGER      NOT NULL DEFAULT 0,
    role          VARCHAR(255) NOT NULL,
    score         INTEGER      DEFAULT 0,
    CONSTRAINT pk_logistic PRIMARY KEY (id),
    CONSTRAINT fk_logistic_staff FOREIGN KEY (id) REFERENCES staff (id)
);

-- ------------------------------------------------------------
-- event: eventos del sistema
-- ------------------------------------------------------------
CREATE TABLE event (
    id                            INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    name                          VARCHAR(255) NOT NULL,
    place_id                      INTEGER      NOT NULL,
    state                         VARCHAR(255) NOT NULL,
    date                          DATE         NOT NULL,
    start_time                    INTEGER      NOT NULL DEFAULT 0,
    end_time                      INTEGER      NOT NULL DEFAULT 0,
    max_coordinators              INTEGER      NOT NULL DEFAULT 0,
    max_logistics                 INTEGER      NOT NULL DEFAULT 0,
    max_logistics_per_coordinator INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_event PRIMARY KEY (id),
    CONSTRAINT fk_event_place FOREIGN KEY (place_id) REFERENCES place (id)
);

-- ------------------------------------------------------------
-- event_assignment: asignación de personal a un evento
-- Un mismo staff no puede estar dos veces en el mismo evento.
-- ------------------------------------------------------------
CREATE TABLE event_assignment (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    staff_id       INTEGER      NOT NULL,
    event_id       INTEGER      NOT NULL,
    assigned_by_id INTEGER      NOT NULL,
    staff_role     VARCHAR(255) NOT NULL,
    CONSTRAINT pk_event_assignment PRIMARY KEY (id),
    CONSTRAINT uk_event_assignment_staff_event UNIQUE (staff_id, event_id),
    CONSTRAINT fk_event_assignment_staff FOREIGN KEY (staff_id) REFERENCES staff (id),
    CONSTRAINT fk_event_assignment_event FOREIGN KEY (event_id) REFERENCES event (id),
    CONSTRAINT fk_event_assignment_assigned_by FOREIGN KEY (assigned_by_id) REFERENCES staff (id)
);

-- ------------------------------------------------------------
-- Índices sobre claves foráneas (mejoran las consultas)
-- ------------------------------------------------------------
CREATE INDEX idx_event_place ON event (place_id);
CREATE INDEX idx_event_assignment_staff ON event_assignment (staff_id);
CREATE INDEX idx_event_assignment_event ON event_assignment (event_id);
CREATE INDEX idx_event_assignment_assigned_by ON event_assignment (assigned_by_id);
